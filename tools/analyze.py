"""Audio analysis → data/derived/analysis.js (band energies, onsets and vocal energy at 60 fps + BPM / phase of the first beat).

    python tools/analyze.py            # reads data/audio/audio.wav (decoded from ref/audio/ by tools/audio.py, which runs this script automatically at the end)

Loaded with a <script> tag (no fetch). The beat pulse, camera zoom and particle bursts in the picture all read it; lyric-tool/lyrics.py uses its BPM / phase for the 16th-note grid.
The BPM is searched for within bpm_range in project.json: autocorrelation easily locks onto half or double the tempo, so a narrower range is more reliable.
"""

import json

import numpy as np
from scipy import ndimage, signal
from scipy.io import wavfile

from paths import AUDIO, DERIVED, config

FPS = 60
BPM_LO, BPM_HI = config().get('bpm_range', [70, 200])

sr, x = wavfile.read(AUDIO / 'audio.wav')
x = x.astype(np.float32) / 32768
mono = x.mean(1)
hop = sr // FPS
nper = 2048
f, t, Z = signal.stft(mono, sr, nperseg=nper, noverlap=nper - hop, boundary=None, padded=False)
S = np.abs(Z)


def band(lo, hi):
    m = (f >= lo) & (f < hi)
    e = np.log1p(30 * S[m].mean(0))
    return e / (np.percentile(e, 99.5) + 1e-9)


low, mid, high = band(30, 160), band(300, 3000), band(5000, 14000)
rms = np.sqrt(ndimage.uniform_filter1d(mono ** 2, hop)[::hop][:len(low)])
rms = rms / (np.percentile(rms, 99.5) + 1e-9)

# Onsets: spectral flux
flux = np.maximum(0, np.diff(np.log1p(100 * S), axis=1)).sum(0)
flux = np.concatenate([[0], flux])
flux = flux / (np.percentile(flux, 99.5) + 1e-9)

# Vocals: centre channel + harmonics (median along time) + the vocal band
_, _, L = signal.stft(x[:, 0], sr, nperseg=nper, noverlap=nper - hop, boundary=None, padded=False)
_, _, R = signal.stft(x[:, 1], sr, nperseg=nper, noverlap=nper - hop, boundary=None, padded=False)
sim = 1 - np.abs(np.abs(L) - np.abs(R)) / (np.abs(L) + np.abs(R) + 1e-9)
ph = np.cos(np.angle(L) - np.angle(R))
C = np.abs((L + R) / 2) * np.clip(sim, 0, 1) ** 4 * np.clip(ph, 0, 1) ** 2
Hm = ndimage.median_filter(C, size=(1, 17))
Pm = ndimage.median_filter(C, size=(17, 1))
Hs = C * (Hm ** 2 / (Hm ** 2 + Pm ** 2 + 1e-12))
vb = (f > 280) & (f < 3500)
vox = ndimage.uniform_filter1d(np.log1p(40 * Hs[vb].sum(0)), 5)
vox = vox / (np.percentile(vox, 99.5) + 1e-9)

# BPM: autocorrelation of the onsets, restricted to bpm_range in project.json
o = flux - ndimage.uniform_filter1d(flux, FPS)
ac = np.correlate(o, o, 'full')[len(o) - 1:]
lags = np.arange(len(ac)) / FPS
cand = (lags > 60 / BPM_HI) & (lags < 60 / BPM_LO)
lag0 = lags[cand][np.argmax(ac[cand])]
# Refine: scan within ±1.5% and take the period and phase that put the beats on the onset peaks
best = (-1, 0, 0)
lowo = np.maximum(0, low - ndimage.uniform_filter1d(low, FPS // 2))
for P in np.linspace(lag0 * .985, lag0 * 1.015, 301):
    for ph0 in np.linspace(0, P, 48, endpoint=False):
        idx = np.round((ph0 + np.arange(0, len(o) / FPS - ph0, P)) * FPS).astype(int)
        idx = idx[idx < len(o)]
        sc = o[idx].sum() + lowo[idx].sum()
        if sc > best[0]:
            best = (sc, P, ph0)
_, P, phase = best
bpm = 60 / P
n = min(len(low), len(mid), len(high), len(rms), len(flux), len(vox))
r3 = lambda a: [round(float(v), 3) for v in np.clip(a[:n], 0, 1.5)]
out = dict(duration=round(len(mono) / sr, 3), fps=FPS, bpm=round(bpm, 3), phase=round(phase, 4),
           low=r3(low), mid=r3(mid), high=r3(high), rms=r3(rms), onset=r3(flux), vox=r3(vox))
DERIVED.mkdir(parents=True, exist_ok=True)
(DERIVED / 'analysis.js').write_text(
    '// Generated by tools/analyze.py; do not edit by hand\nwindow.ANALYSIS = ' + json.dumps(out, separators=(',', ':')) + ';\n', 'utf-8')
print(f'{n} frames  bpm {bpm:.3f}  phase {phase:.3f}s  duration {out["duration"]}s')
